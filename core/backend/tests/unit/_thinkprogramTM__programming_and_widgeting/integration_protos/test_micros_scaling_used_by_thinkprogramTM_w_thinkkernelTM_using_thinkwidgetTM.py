"""
E2E proof sheet: scalable datacore micros through ThinkProgramTM,
ThinkKernelTM, ThinkWidgetTM, datomaton lifecycle, validation, coercion,
renderer shell hydration, and runtime history.

Purpose
-------
This sheet proves that adding a new micro type to the base platform datacore
does not require hardcoded changes in ThinkProgramTM, ThinkKernelTM,
ThinkWidgetTM, datomaton widgets, multiframespec UI lowering, manual partial
fill validation, mount/reexplode lifecycle memory, final commit handling, or
kernel history wiring.

The test installs a synthetic micro type at test time:

    rating_scale_e2e

and proves it flows through:

    MICRO_TYPES
      -> datum shell generated by ThinkWidgetTM mount/reexplode
      -> multiframespec UI context
      -> raw DatumFillValidator semantic validation
      -> accepted-fill coercion
      -> datomaton q["raw_fill"] and q["partial_fill"]
      -> ThinkWidgetTM fill_data["current_fills"]
      -> lifecycle memory state
      -> final commit
      -> ThinkKernelTM history wires
      -> highest ThinkProgram-like authoring surface

Core contract proved here
-------------------------
1. ThinkProgram authors do not author micros.

   The highest app-building surface describes widgets, args, wires, and flow.
   It lowers to ThinkKernel datums with:

       "micros": []

   Usable datum shells are produced by mount-shelling ThinkWidgets.

2. New micros are data-driven.

   No production layer should need a switch/case for rating_scale_e2e. The
   shell carries the micro type name, args, style, validators, and requiredness.

3. Validation and coercion are separate.

   DatumFillValidator validates raw data and returns raw accepted values.
   Runtime-style helpers canonicalize accepted fills through MICRO_TYPES.

4. Widgets see the right data.

   q["raw_fill"] preserves raw submitted/merged data.
   q["partial_fill"] is accepted and canonical/coerced data.
   ThinkWidgetTM fill_data["current_fills"] is canonical/coerced data.

5. Kernel history remains widget/lifecycle-data oriented.

   A downstream ThinkWidget reads prior lifecycle writes through
   q["datum"]["args"]["__kernel"]["past_wires"], without the kernel needing to
   know or hardcode the new micro type.
"""

