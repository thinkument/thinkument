def deepcopy_json(value: Any) -> Any:
    return json.loads(json.dumps(value, sort_keys=True))


def require_mapping(value: Any, path: str) -> Dict[str, Any]:
    if not isinstance(value, Mapping):
        raise ValueError(f"{path} must be mapping")
    return dict(value)


def require_nonempty_str(value: Any, path: str) -> str:
    s = str(value or "").strip()
    if not s:
        raise ValueError(f"{path} must be non-empty string")
    return s


def reject_unknown_keys(obj: Mapping[str, Any], allowed: set[str], *, path: str) -> None:
    extra = set(dict(obj)) - set(allowed)
    if extra:
        raise ValueError(f"{path} has unknown keys: {sorted(extra)}")


def assert_no_key_recursively(value: Any, forbidden_key: str, *, path: str) -> None:
    if isinstance(value, Mapping):
        if forbidden_key in value:
            raise ValueError(f"{path} may not author {forbidden_key!r}")
        for key, child in value.items():
            assert_no_key_recursively(child, forbidden_key, path=f"{path}.{key}")
    elif isinstance(value, list):
        for i, child in enumerate(value):
            assert_no_key_recursively(child, forbidden_key, path=f"{path}[{i}]")


def deep_merge(base: Mapping[str, Any], patch: Mapping[str, Any]) -> Dict[str, Any]:
    out = deepcopy_json(dict(base or {}))
    for key, value in dict(patch or {}).items():
        if key in out and isinstance(out[key], Mapping) and isinstance(value, Mapping):
            out[key] = deep_merge(out[key], value)
        else:
            out[key] = deepcopy_json(value)
    return out


def safe_alias(*parts: str) -> str:
    raw = "_".join(str(p) for p in parts if str(p))
    out = []
    for ch in raw:
        out.append(ch if ch.isalnum() or ch == "_" else "_")
    return "_".join("".join(out).split("_"))


def validate_args_against_kernel_contract(
    *,
    logical_widget_id: str,
    widget_name: str,
    args: Mapping[str, Any],
    path: str,
) -> Dict[str, Any]:
    contract = kernel_widget_class_repr_v1(widget_name)["inferred_kernel_contract_spec"]
    arg_specs = dict(contract.get("args") or {})
    arg_map = dict(args or {})

    unknown = set(arg_map) - set(arg_specs)
    if unknown:
        raise ValueError(
            f"{path} logical widget {logical_widget_id!r} has unknown args: "
            f"{sorted(unknown)}"
        )

    for arg_name, spec_raw in arg_specs.items():
        spec = dict(spec_raw)
        required = bool(spec.get("required", False))
        typ = str(spec.get("type") or "json")

        if required and arg_name not in arg_map:
            raise ValueError(
                f"{path} logical widget {logical_widget_id!r} "
                f"missing required arg {arg_name!r}"
            )

        if arg_name in arg_map:
            value = arg_map[arg_name]
            ok = True
            if typ == "str":
                ok = isinstance(value, str)
            elif typ == "int":
                ok = isinstance(value, int) and not isinstance(value, bool)
            elif typ == "float":
                ok = isinstance(value, (int, float)) and not isinstance(value, bool)
            elif typ == "bool":
                ok = isinstance(value, bool)
            elif typ == "dict":
                ok = isinstance(value, Mapping)
            elif typ == "list":
                ok = isinstance(value, list)
            elif typ == "list[str]":
                ok = isinstance(value, list) and all(isinstance(x, str) for x in value)
            elif typ == "list[int]":
                ok = isinstance(value, list) and all(
                    isinstance(x, int) and not isinstance(x, bool) for x in value
                )
            else:
                json.dumps(value, sort_keys=True)

            if not ok:
                raise ValueError(
                    f"{path} logical widget {logical_widget_id!r} "
                    f"arg {arg_name!r} must be {typ}"
                )

    return deepcopy_json(arg_map)


def validate_wires_against_kernel_contract(
    *,
    logical_widget_id: str,
    widget_name: str,
    wires: Mapping[str, Any],
    path: str,
) -> Dict[str, Any]:
    contract = kernel_widget_class_repr_v1(widget_name)["inferred_kernel_contract_spec"]
    wire_specs = dict(contract.get("past_wires") or {})
    wire_map = dict(wires or {})

    unknown = set(wire_map) - set(wire_specs)
    if unknown:
        raise ValueError(
            f"{path} logical widget {logical_widget_id!r} has unknown wires: "
            f"{sorted(unknown)}"
        )

    for wire_name, wire_spec in wire_map.items():
        if wire_spec is None:
            continue
        if not isinstance(wire_spec, Mapping):
            raise ValueError(f"{path}.wires[{wire_name!r}] must be mapping or null")
        if "from" not in wire_spec:
            raise ValueError(f"{path}.wires[{wire_name!r}] missing from")
        if "history" not in wire_spec:
            raise ValueError(f"{path}.wires[{wire_name!r}] missing history")

    return deepcopy_json(wire_map)


def history_spec(raw: Any, *, path: str) -> Dict[str, Any]:
    h = require_mapping(raw, path)
    select = str(h.get("select") or "latest")
    if select not in {"latest", "all"}:
        raise ValueError(f"{path}.select must be latest|all")

    required = h.get("required", False)
    if not isinstance(required, bool):
        raise ValueError(f"{path}.required must be boolean")

    max_results = h.get("max_results", 20)
    if not isinstance(max_results, int) or isinstance(max_results, bool):
        raise ValueError(f"{path}.max_results must be integer")

    return {
        "select": select,
        "required": required,
        "max_results": max_results,
    }


def lower_micro_scale_thinkprogram_to_kernel(program: Mapping[str, Any]) -> list[Dict[str, Any]]:
    p = require_mapping(program, "program")
    reject_unknown_keys(p, _ALLOWED_TOP_KEYS, path="program")

    if str(p.get("kind") or "") != TP_KIND:
        raise ValueError(f"program.kind must be {TP_KIND!r}")

    if str(p.get("surface_version") or "") != "v1":
        raise ValueError("program.surface_version must be 'v1'")

    assert_no_key_recursively(p.get("run", {}), "micros", path="program.run")

    run = require_mapping(p.get("run"), "program.run")
    reject_unknown_keys(run, _ALLOWED_RUN_KEYS, path="program.run")

    program_map = require_mapping(run.get("program"), "program.run.program")
    reject_unknown_keys(program_map, _ALLOWED_PROGRAM_KEYS, path="program.run.program")

    info = require_mapping(program_map.get("info"), "program.run.program.info")
    reject_unknown_keys(info, _ALLOWED_INFO_KEYS, path="program.run.program.info")

    program_id = require_nonempty_str(info.get("id"), "program.run.program.info.id")
    require_nonempty_str(info.get("title"), "program.run.program.info.title")

    widgets = require_mapping(program_map.get("widgets"), "program.run.program.widgets")
    flow = program_map.get("flow")
    if not isinstance(flow, list) or not flow:
        raise ValueError("program.run.program.flow must be non-empty list")

    normalized_widgets: Dict[str, Dict[str, Any]] = {}

    for logical_widget_id_raw, widget_raw in widgets.items():
        logical_widget_id = require_nonempty_str(
            logical_widget_id_raw,
            "logical widget id",
        )
        wd = require_mapping(
            widget_raw,
            f"program.run.program.widgets[{logical_widget_id!r}]",
        )
        reject_unknown_keys(
            wd,
            _ALLOWED_WIDGET_KEYS,
            path=f"program.run.program.widgets[{logical_widget_id!r}]",
        )

        widget_name = require_nonempty_str(
            wd.get("widget"),
            f"program.run.program.widgets[{logical_widget_id!r}].widget",
        )

        contract = kernel_widget_class_repr_v1(widget_name)[
            "inferred_kernel_contract_spec"
        ]
        if not bool(contract.get("enforce_no_premount_shell", False)):
            raise ValueError(
                "highest ThinkProgram surface only admits mount-shelling widgets; "
                f"widget {widget_name!r} is not enforce_no_premount_shell=true"
            )

        args = validate_args_against_kernel_contract(
            logical_widget_id=logical_widget_id,
            widget_name=widget_name,
            args=dict(wd.get("args") or {}),
            path=f"program.run.program.widgets[{logical_widget_id!r}]",
        )

        wires = validate_wires_against_kernel_contract(
            logical_widget_id=logical_widget_id,
            widget_name=widget_name,
            wires=dict(wd.get("wires") or {}),
            path=f"program.run.program.widgets[{logical_widget_id!r}]",
        )

        lifecycle = deep_merge(
            {
                "mount_explode": True,
                "max_reexplosions": 10,
                "max_proc_notes": 0,
                "max_messages": 8,
            },
            dict(wd.get("lifecycle") or {}),
        )
        lifecycle["mount_explode"] = True

        normalized_widgets[logical_widget_id] = {
            "logical_widget_id": logical_widget_id,
            "widget": widget_name,
            "title": str(wd.get("title") or logical_widget_id),
            "args": args,
            "wires": wires,
            "lifecycle": lifecycle,
            "tags": list(wd.get("tags") or []),
            "system_flags": dict(wd.get("system_flags") or {}),
            "authoritative": bool(wd.get("authoritative", True)),
        }

    explicit: list[Dict[str, Any]] = []
    prior: Dict[str, list[Appearance]] = {}
    seen_flow_ids: set[str] = set()

    for flow_index, flow_raw in enumerate(flow):
        f = require_mapping(flow_raw, f"program.run.program.flow[{flow_index}]")
        reject_unknown_keys(
            f,
            _ALLOWED_FLOW_KEYS,
            path=f"program.run.program.flow[{flow_index}]",
        )

        flow_id = require_nonempty_str(f.get("id"), f"flow[{flow_index}].id")
        if flow_id in seen_flow_ids:
            raise ValueError(f"duplicate flow id: {flow_id!r}")
        seen_flow_ids.add(flow_id)

        flow_widgets = f.get("widgets")
        if not isinstance(flow_widgets, list) or not flow_widgets:
            raise ValueError(f"flow {flow_id!r}.widgets must be non-empty list")
        if len(set(flow_widgets)) != len(flow_widgets):
            raise ValueError(f"flow {flow_id!r} may not repeat a widget")
        for logical_widget_id in flow_widgets:
            if logical_widget_id not in normalized_widgets:
                raise ValueError(
                    f"flow {flow_id!r} references unknown widget "
                    f"{logical_widget_id!r}"
                )

        overrides = dict(f.get("overrides") or {})
        reject_unknown_keys(
            overrides,
            _ALLOWED_OVERRIDE_KEYS,
            path=f"flow {flow_id!r}.overrides",
        )

        step_id = f"{program_id}.{flow_id}"
        form_id = f"{program_id}.{flow_id}.form"

        k: Dict[str, Any] = {
            "kind": "think_kernel_step_v1",
            "kernel_args_surface_version": "v1",
            "step": {
                "id": step_id,
                "title": str(f.get("title") or flow_id),
            },
            "form": {
                "id": form_id,
                "title": str(f.get("title") or flow_id),
            },
            "frame": {
                "id": "frame",
                "title": str(f.get("title") or flow_id),
            },
            "span": {
                "id": "span",
                "title": str(f.get("title") or flow_id),
            },
            "history_queries": {},
            "datums": [],
            "kernel_flags": {
                "copy_form_frame_span_args_into_each_datum": True,
                "mount_explode_default": True,
            },
        }

        current_appearances: list[Appearance] = []

        authoritative = f.get("authoritative")
        if authoritative is not None:
            if not isinstance(authoritative, list):
                raise ValueError(f"flow {flow_id!r}.authoritative must be list[bool]")
            if len(authoritative) != len(flow_widgets):
                raise ValueError(
                    f"flow {flow_id!r}.authoritative length must match widgets"
                )
            if not all(isinstance(x, bool) for x in authoritative):
                raise ValueError(f"flow {flow_id!r}.authoritative must be list[bool]")

        for widget_position, logical_widget_id in enumerate(flow_widgets):
            base = deepcopy_json(normalized_widgets[logical_widget_id])
            args = deep_merge(
                base["args"],
                dict(dict(overrides.get("args") or {}).get(logical_widget_id) or {}),
            )
            lifecycle = deep_merge(
                base["lifecycle"],
                dict(dict(overrides.get("lifecycle") or {}).get(logical_widget_id) or {}),
            )
            lifecycle["mount_explode"] = True
            system_flags = deep_merge(
                base["system_flags"],
                dict(
                    dict(overrides.get("system_flags") or {}).get(logical_widget_id)
                    or {}
                ),
            )
            system_flags["logical_widget_id"] = logical_widget_id

            wires = deepcopy_json(base["wires"])
            for wire_name, wire_value in dict(
                dict(overrides.get("wires") or {}).get(logical_widget_id) or {}
            ).items():
                if wire_value is None:
                    wires.pop(wire_name, None)
                else:
                    wires[wire_name] = deepcopy_json(wire_value)

            widget_name = str(base["widget"])
            validate_args_against_kernel_contract(
                logical_widget_id=logical_widget_id,
                widget_name=widget_name,
                args=args,
                path=f"flow {flow_id!r}.{logical_widget_id}",
            )
            validate_wires_against_kernel_contract(
                logical_widget_id=logical_widget_id,
                widget_name=widget_name,
                wires=wires,
                path=f"flow {flow_id!r}.{logical_widget_id}",
            )

            past_wires: Dict[str, list[str]] = {}

            for wire_name, wire_raw in dict(wires or {}).items():
                wire = require_mapping(
                    wire_raw,
                    f"flow {flow_id!r}.{logical_widget_id}.wires[{wire_name!r}]",
                )
                h = history_spec(
                    wire.get("history"),
                    path=f"flow {flow_id!r}.{logical_widget_id}.wires[{wire_name!r}].history",
                )
                source_id = require_nonempty_str(
                    wire.get("from"),
                    f"flow {flow_id!r}.{logical_widget_id}.wires[{wire_name!r}].from",
                )

                appearances = list(prior.get(source_id) or [])
                if not appearances:
                    if h["required"]:
                        raise ValueError(
                            f"required wire {logical_widget_id}.{wire_name} "
                            f"has no prior source {source_id!r}"
                        )
                    continue

                selected = appearances if h["select"] == "all" else [appearances[-1]]
                aliases: list[str] = []

                for appearance in selected:
                    alias = safe_alias(
                        logical_widget_id,
                        wire_name,
                        source_id,
                        h["select"],
                        appearance.step_id,
                    )
                    k["history_queries"][alias] = {
                        "from_step": appearance.step_id,
                        "datum_id": appearance.datum_id,
                        "write_kind": WRITE_KIND_DATUM_LIFECYCLE,
                        "include_value": True,
                        "required": bool(h["required"]),
                        "select": h["select"],
                        "max_results": int(h["max_results"]),
                    }
                    aliases.append(alias)

                if aliases:
                    past_wires[wire_name] = aliases

            datum = {
                "id": logical_widget_id,
                "widget": widget_name,
                "title": str(
                    dict(overrides.get("title") or {}).get(
                        logical_widget_id,
                        base["title"],
                    )
                ),
                # Important ThinkProgram law:
                # app authors do not author micros. The compiler emits empty
                # premount shells, and widgets create usable shells on mount.
                "micros": [],
                "lifecycle": lifecycle,
                "past_wires": past_wires,
                "args": args,
                "tags": list(base["tags"]),
                "system_flags": system_flags,
                "authoritative": (
                    authoritative[widget_position]
                    if authoritative is not None
                    else bool(base["authoritative"])
                ),
            }
            k["datums"].append(datum)
            current_appearances.append(
                Appearance(
                    logical_widget_id=logical_widget_id,
                    step_id=step_id,
                    datum_id=logical_widget_id,
                )
            )

        if not any(bool(d.get("authoritative", True)) for d in k["datums"]):
            raise ValueError(f"flow {flow_id!r} lowers to no authoritative datums")

        explicit.append(k)
        for appearance in current_appearances:
            prior.setdefault(appearance.logical_widget_id, []).append(appearance)

    return validate_kernel_program_v1(explicit)


