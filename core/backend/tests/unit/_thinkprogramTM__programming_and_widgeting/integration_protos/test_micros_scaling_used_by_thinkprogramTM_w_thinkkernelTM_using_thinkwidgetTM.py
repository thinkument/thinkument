@thinkwidgetTM_config(
    TP_SOURCE_WIDGET,
    overwrite=True,
    missing_signal_handler_outcome=MISSING_SIGNAL_FALLBACK_TO_FILL,
    enforce_no_premount_shell=True,
    args={
        "seed": {"type": "str", "required": True},
        "stars": {"type": "int", "required": False, "default": 5},
    },
    wires={},
)
class MicroScaleSourceWidget(DatumLifecycleWidget):
    def _on_mount(self, position, fill_data, limits, stats):
        shell = dict(fill_data["fill_shell"])
        datum_args = dict(shell.get("args") or {})
        kernel_args = dict(datum_args.get("__kernel") or {})

        self.mount_seen_initial_micros = list(shell.get("micros") or [])
        self.mount_seen_user_args = {
            k: v for k, v in datum_args.items() if k != "__kernel"
        }
        self.mount_seen_kernel = {
            "step_id": dict(kernel_args.get("step") or {}).get("id"),
            "form_id": dict(kernel_args.get("form") or {}).get("id"),
            "frame_id": dict(kernel_args.get("frame") or {}).get("id"),
            "span_id": dict(kernel_args.get("span") or {}).get("id"),
            "past_wires": dict(kernel_args.get("past_wires") or {}),
            "system_flags": dict(kernel_args.get("system_flags") or {}),
            "authoritative": bool(kernel_args.get("authoritative", False)),
        }
        self.mount_root_pollution = {
            key: key in self._q
            for key in (
                "kernel",
                "step",
                "form",
                "frame",
                "span",
                "past_wires",
                "history_queries",
            )
        }

        lifecycle = dict(shell.get("lifecycle") or {})
        lifecycle["widget"] = TP_SOURCE_WIDGET

        return Reexplode(
            next_fill_shell={
                "id": shell.get("id", position["datum_id"]),
                "title": "Source rating shell generated by mount",
                "micros": [
                    rating_micro(
                        "score",
                        required=True,
                        stars=int(self.mount_seen_user_args["stars"]),
                    ),
                    text_micro("note", required=False),
                ],
                "macro_validation_lambdas": [
                    f"{VALIDATOR_MODULE}:rating_even_macro",
                ],
                "lifecycle": lifecycle,
            },
        )

    def _on_fill(self, signal, position, fill_data, limits, stats):
        shell = dict(fill_data["fill_shell"])
        current = dict(fill_data["current_fills"])
        changed = dict(fill_data["changed_fills"])

        score_micro = next(m for m in shell["micros"] if m["name"] == "score")

        self.fill_seen_micro_type = score_micro["type"]
        self.fill_seen_micro_args = dict(score_micro.get("args") or {})
        self.fill_seen_micro_style = dict(score_micro.get("style") or {})
        self.fill_seen_current_score = current.get("score")
        self.fill_seen_current_score_type = type(current.get("score")).__name__
        self.fill_seen_changed_score = changed.get("score")
        self.fill_seen_changed_score_type = type(changed.get("score")).__name__
        self.fill_seen_shell_satisfaction = bool(
            fill_data["shell_satisfaction_check"]
        )
        self.commit = {
            "datum_id": position["datum_id"],
            "score": current.get("score"),
            "score_type": type(current.get("score")).__name__,
            "note": current.get("note"),
            "micro_type": score_micro["type"],
        }
        return True


